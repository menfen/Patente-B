// Builds src/PatenteB.Web/wwwroot/data/questions.js from the two MIT-licensed sources in _downloads:
//   - Ed0ardo/QuizPatenteB: official questions grouped by chapter and sub-topic, plus sign images
//   - MathKidsClub/Italian-Driving-Theory-Tester: English translation, trap words and sign meaning per question
// and data/questions-ar.js from the Egyptian Arabic translations in tools/topics-ar.json and tools/ar/questions (see ar-export.mjs).
// Usage: node tools/build-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { arHash, explHash, loadArabic, loadExplanations } from './ar-lib.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dl = path.join(root, '_downloads');
const out = path.join(root, 'src', 'PatenteB.Web', 'wwwroot');

const ed = JSON.parse(fs.readFileSync(path.join(dl, 'ed', 'quiz.json'), 'utf8'));
const mkcSrc = fs.readFileSync(path.join(dl, 'mkc', 'questions.js'), 'utf8')
  .replace(/^\s*window\.QUESTIONS\s*=\s*/, '').replace(/;\s*$/, '');
const mkc = JSON.parse(mkcSrc);
const topicsEn = JSON.parse(fs.readFileSync(path.join(root, 'tools', 'topics-en.json'), 'utf8'));
const imgSrcDir = path.join(dl, 'ed_zip', 'QuizPatenteB-main', 'img_sign');

const norm = s => s.normalize('NFC').toLowerCase().replace(/[’`]/g, "'").replace(/[^a-z0-9àèéìòù']+/g, ' ').trim();
const tokens = s => new Set(norm(s).split(' '));
const exact = new Map(mkc.map(q => [norm(q.it), q]));

function similarity(a, b) {
  let inter = 0;
  for (const t of a) if (b.has(t)) inter++;
  return inter / (a.size + b.size - inter);
}
const mkcTokens = mkc.map(q => [q, tokens(q.it)]);
function findEnglish(it) {
  const hit = exact.get(norm(it));
  if (hit) return { q: hit, fuzzy: false };
  const tk = tokens(it);
  let best = null, bestScore = 0;
  for (const [q, t] of mkcTokens) {
    const s = similarity(tk, t);
    if (s > bestScore) { bestScore = s; best = q; }
  }
  return bestScore >= 0.85 ? { q: best, fuzzy: true } : null;
}

const prettify = slug => slug.replace(/-/g, ' ').replace(/^\w/, c => c.toUpperCase());
const usedImages = new Set();
// "Why, according to the law" explanations per question (tools/expl, see expl-export.mjs): English here, Arabic in questions-ar.js.
const expl = loadExplanations(root);
let explained = 0;
let total = 0, matched = 0, fuzzy = 0, missingNames = [];
let id = 0;

const chapters = Object.entries(ed).map(([chId, subs]) => ({
  id: chId,
  subs: Object.entries(subs).map(([subId, qs]) => {
    let en = topicsEn[chId]?.[subId];
    if (!en) {
      const fig = subId.match(/^figura-(\d+)$/);
      if (fig) en = `Intersection diagram ${fig[1]}`;
      else { en = prettify(subId); missingNames.push(`${chId}/${subId}`); }
    }
    return {
      id: subId,
      it: prettify(subId),
      en,
      qs: qs.map(q => {
        total++;
        const img = q.img ? path.basename(q.img, '.png') : '';
        if (img) usedImages.add(img);
        const item = { i: ++id, t: q.q, a: q.a ? 1 : 0 };
        if (img) item.m = img;
        const found = findEnglish(q.q);
        // A near-miss match must also agree on the answer, so a dropped "non" can't attach the wrong English.
        if (found && (!found.fuzzy || found.q.answer === !!q.a)) {
          matched++;
          if (found.fuzzy) fuzzy++;
          const m = found.q;
          if (m.en) item.e = m.en;
          if (m.trick) item.x = m.trick;
          if (m.sign) item.s = m.sign;
          const kw = (m.keywords || []).filter(k => k.phrase).map(k => [k.phrase, k.why || '']);
          if (kw.length) item.k = kw;
        }
        const ex = expl.get(explHash(q.q, q.a));
        if (ex) { item.w = ex[0]; explained++; }
        return item;
      }),
    };
  }),
}));

fs.mkdirSync(path.join(out, 'data'), { recursive: true });
fs.writeFileSync(
  path.join(out, 'data', 'questions.js'),
  '// Generated by tools/build-data.mjs - do not edit by hand.\n' +
  '// Questions: Ed0ardo/QuizPatenteB (MIT). English, trap words, sign notes: MathKidsClub/Italian-Driving-Theory-Tester (MIT).\n' +
  'window.QDATA=' + JSON.stringify({ chapters }) + ';\n'
);

// Arabic: per question [translation, trap note, picture note, [trap-word notes]]; empty strings fall back to English.
const arText = loadArabic(root);
const topicsAr = JSON.parse(fs.readFileSync(path.join(root, 'tools', 'topics-ar.json'), 'utf8'));
const qAr = {}, subAr = {};
let arFields = 0, arMissing = 0;
const ar = t => { if (!t) return ''; const v = arText.get(arHash(t)); if (v) arFields++; else arMissing++; return v || ''; };
for (const ch of chapters) for (const sub of ch.subs) {
  const fig = sub.id.match(/^figura-(\d+)$/);
  const name = topicsAr[ch.id]?.[sub.id] || (fig ? `رسم تقاطع ${fig[1]}` : '');
  if (name) subAr[`${ch.id}/${sub.id}`] = name;
  for (const q of sub.qs) {
    const ex = expl.get(explHash(q.t, q.a));
    const row = [ar(q.e), ar(q.x), ar(q.s), (q.k || []).map(([, w]) => ar(w)), (ex && ex[1]) || ''];
    while (row.length && (row[row.length - 1] === '' || (Array.isArray(row[row.length - 1]) && !row[row.length - 1].some(Boolean)))) row.pop();
    if (row.length) qAr[q.i] = row;
  }
}
fs.writeFileSync(
  path.join(out, 'data', 'questions-ar.js'),
  '// Generated by tools/build-data.mjs - do not edit by hand. Egyptian Arabic, translated from the English texts.\n' +
  'window.TOPICS_AR=' + JSON.stringify(subAr) + ';\n' +
  'window.QDATA_AR=' + JSON.stringify(qAr) + ';\n'
);

const imgOut = path.join(out, 'img', 'signs');
fs.mkdirSync(imgOut, { recursive: true });
let copied = 0, missingImg = [];
for (const n of usedImages) {
  const src = path.join(imgSrcDir, `${n}.png`);
  if (fs.existsSync(src)) { fs.copyFileSync(src, path.join(imgOut, `${n}.png`)); copied++; }
  else missingImg.push(n);
}

console.log({ total, matched, fuzzy, unmatched: total - matched, images: copied, missingImg, missingNames, arabic: { translated: arFields, missing: arMissing }, explained });
